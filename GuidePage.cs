using AlMithaq.Shared.Controls;

namespace AlMithaq;

public sealed class GuidePage : ContentPage
{
    public GuidePage()
    {
        Ui.Page(this, "دليل استخدام الميثاق");
        var content = Ui.Stack(Ui.Label("كيف تستخدم الميثاق؟", 22, true),
            Ui.Label("اختر قسمًا لعرض خطوات استخدامه.", 14));
        content.Padding = 16;
        content.Spacing = 12;
        Add("المصحف والبحث", "اختر سورة أو جزءًا أو صفحة من الفهرس. اسحب للتقليب واضغط مرة لإظهار الأدوات. اضغط مطولًا على آية لعرض خياراتها. في البحث، استمع إلى آية واحدة أو اختر استكمال القراءة من المصحف من قائمة المزيد. غيّر زخرفة العناوين من إعدادات القراءة ← إطار السورة.");
        Add("التلاوة", "اختر القارئ واضغط تشغيل. من ترس المشغّل، اختر أول آية وآخر آية وسرعة التشغيل وعدد مرات تكرار الآية والمقطع. استخدم شريط التقدم للانتقال داخل الآية واضبط الصوت من رمز السماعة. نزّل السورة للاستماع دون إنترنت.");
        Add("الورد وخطة الختمة", "حدّد صفحة البداية وعدد الصفحات في بطاقة الورد. في خطة الختمة اختر المدة وسجّل إتمام الورد لمتابعة تقدمك.");
        Add("الحفظ والمراجعة", "أضف مقطعًا وحدّد أول آية وآخر آية. اختبر حفظك بإخفاء الآيات ثم كشفها، وسجّل تقييمك لتحديد موعد المراجعة.");
        Add("الصلاة والقبلة وقيام الليل", "حدّد موقعك لحساب المواقيت وفعّل الأذان من الإعدادات. افتح القبلة لمعرفة الاتجاه، وقيام الليل لمعرفة وقته وضبط تذكيره.");
        Add("الأذكار والأدعية والسبحة", "اختر تبويب الأذكار أو الأدعية وابحث عن النص. استخدم العداد لتسجيل التكرار، أو افتح السبحة واختر هدفك.");
        Add("حاسبة الزكاة", "اختر نوع المال وأدخل البيانات التي تطلبها الحاسبة، ثم راجع النتيجة وشروط الحساب المعروضة.");
        Add("المظهر والتنبيهات والمصادر", "بدّل المظهر من رمز الشمس والقمر واضبط التنبيهات من الإعدادات. افتح المصادر والتراخيص لمعرفة مراجع المحتوى.");
        Content = new ScrollView { Content = content };

        void Add(string title, string description)
        {
            var details = Ui.Label(description, 14);
            details.IsVisible = false;
            var toggle = Ui.Button(title + "  ＋", () => details.IsVisible = !details.IsVisible, true);
            details.PropertyChanged += (_, e) =>
            {
                if (e.PropertyName == nameof(IsVisible)) toggle.Text = title + (details.IsVisible ? "  −" : "  ＋");
            };
            content.Add(Ui.Card(Ui.Stack(toggle, details)));
        }
    }
}
